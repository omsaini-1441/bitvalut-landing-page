create table if not exists public.recovery_keys (
  user_id uuid primary key references auth.users(id) on delete cascade,
  ciphertext text not null,
  data_iv text not null,
  data_tag text not null,
  wrapped_key text not null,
  key_iv text not null,
  key_tag text not null,
  key_version integer not null default 1 check (key_version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.recovery_keys enable row level security;

create policy "Users can read their recovery envelope"
  on public.recovery_keys for select
  to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users can create their recovery envelope"
  on public.recovery_keys for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can replace their recovery envelope"
  on public.recovery_keys for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their recovery envelope"
  on public.recovery_keys for delete
  to authenticated
  using ((select auth.uid()) = user_id);

create table if not exists public.download_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  release_url text not null,
  user_agent text,
  referrer text,
  created_at timestamptz not null default now()
);

create index if not exists download_events_user_created_idx
  on public.download_events (user_id, created_at desc);

alter table public.download_events enable row level security;

-- No browser-facing policies: only the server-side service role records events.
revoke all on table public.download_events from anon, authenticated;
